/*
 * demo-services.js — made-up county services for the gallery's service list demos. In an app the
 * Deezul CMS supplies them; the links go nowhere.
 *
 * A service is a thing a resident wants to DO ("Pay property taxes"), not a department. `tags`
 * say how it can be done, `keywords` are the words people actually search for, and `popular`
 * marks the handful that belong in "Most requested".
 */
